func TestFindChecksumCoreutilsFormat(t *testing.T) {
	sum := strings.Repeat("ab", 32)
	manifest := sum + "  aksum-linux-amd64\n" + strings.Repeat("cd", 32) + "  SHA256SUMS\n"

	got, err := findChecksum([]byte(manifest), "aksum-linux-amd64")
	if err != nil {
		t.Fatalf("findChecksum: %v", err)
	}
	if got != sum {
		t.Fatalf("got %q, want %q", got, sum)
	}
}

